def test_adversarial_preexisting_corruption_fails_closed() -> None:
    """When a host config has pre-existing syntax errors, engine MUST NOT touch it."""
    with tempfile.TemporaryDirectory() as tmp_dir:
        corrupt_wt = Path(tmp_dir) / "settings.json"
        corrupt_content = '{\n    "profiles": {\n        "list": [ \n            "broken": true\n        ]\n    }\n}'
        corrupt_wt.write_text(corrupt_content, encoding="utf-8")

        # Attempt sync
        res = sync_windows_terminal(corrupt_wt, TOKYO_NIGHT)

        # 1. Must report failure
        assert res.success is False
        assert "syntax error" in res.message.lower() or "aborting" in res.message.lower()

        # 2. File must remain EXACTLY identical byte-for-byte!
        current_content = corrupt_wt.read_text(encoding="utf-8")
        assert current_content == corrupt_content

        # 3. No orphan temp files
        tmp_files = list(Path(tmp_dir).glob("*.omarchy_tmp.*"))
        assert len(tmp_files) == 0


def test_adversarial_complex_wt_preservation() -> None:
    """Torture test: WT config with multiple profiles, custom schemes, comments, and keybindings."""
    complex_wt_config = """// Windows Terminal v1.20 Config
// Generated by Microsoft Windows Terminal
{
    "$schema": "https://aka.ms/terminal-profiles-schema",
    "defaultProfile": "{61c54bbd-c2c6-5271-96e7-009a87ff44bf}",
    "copyOnSelect": false,
    "actions": [
        // Split pane shortcut
        { "command": { "action": "splitPane", "split": "auto" }, "keys": "alt+shift+d" }
    ],
    "profiles": {
        "defaults": {
            // Global default font
            "font": { "face": "Cascadia Code" }
        },
        "list": [
            {
                "guid": "{61c54bbd-c2c6-5271-96e7-009a87ff44bf}",
                "name": "Windows PowerShell",
                "colorScheme": "Campbell"
            },
            {
                "guid": "{2ece5b75-a04f-5632-8085-b9f1d2d0532e}",
                "name": "Omarchy",
                "source": "Windows.Terminal.Wsl",
                // Custom starting directory for Omarchy
                "startingDirectory": "//wsl$/Omarchy/home/developer"
            }
        ]
    },
    "schemes": [
        // Builtin user custom scheme
        {
            "name": "UserSolarized",
            "background": "#002b36",
            "foreground": "#839496"
        }
    ]
}
// End of configuration
"""
    with tempfile.TemporaryDirectory() as tmp_dir:
        wt_path = Path(tmp_dir) / "settings.json"
        wt_path.write_text(complex_wt_config, encoding="utf-8")

        # Sync Catppuccin Mocha
        res = sync_windows_terminal(wt_path, CATPPUCCIN_MOCHA, target_profile="Omarchy")
        assert res.success is True

        new_text, _ = safe_read_text(wt_path)

        # 1. Verify all user comments survived
        assert "// Windows Terminal v1.20 Config" in new_text
        assert "// Split pane shortcut" in new_text
        assert "// Global default font" in new_text
        assert "// Custom starting directory for Omarchy" in new_text
        assert "// Builtin user custom scheme" in new_text
        assert "// End of configuration" in new_text

        # 2. Verify keybindings survived
        assert '"action": "splitPane"' in new_text

        # 3. Verify user custom scheme survived
        parsed = parse_jsonc(new_text)
        scheme_names = [s["name"] for s in parsed["schemes"]]
        assert "UserSolarized" in scheme_names
        assert "Catppuccin Mocha" in scheme_names

        # 4. Verify Omarchy profile updated with theme, but startingDirectory preserved
        omarchy_p = next(p for p in parsed["profiles"]["list"] if p["name"] == "Omarchy")
        assert omarchy_p["colorScheme"] == "Catppuccin Mocha"
        assert omarchy_p["startingDirectory"] == "//wsl$/Omarchy/home/developer"

        # 5. Verify Windows PowerShell profile untouched
        pwsh_p = next(p for p in parsed["profiles"]["list"] if p["name"] == "Windows PowerShell")
        assert pwsh_p["colorScheme"] == "Campbell"


def test_adversarial_vscode_customizations_merge() -> None:
    """VS Code settings must merge terminal colors without destroying editor colors or comments."""
    existing_vsc = """// VS Code User Settings
{
    "editor.fontSize": 14,
    // Custom non-terminal editor tokens
    "workbench.colorCustomizations": {
        "editor.background": "#1e1e1e",
        "activityBar.background": "#333333"
    }
}
"""
    with tempfile.TemporaryDirectory() as tmp_dir:
        vsc_path = Path(tmp_dir) / "settings.json"
        vsc_path.write_text(existing_vsc, encoding="utf-8")

        res = sync_vscode(vsc_path, NORD)
        assert res.success is True

        updated_text, _ = safe_read_text(vsc_path)

        # 1. Comments preserved
        assert "// VS Code User Settings" in updated_text

        # 2. Existing editor settings preserved
        parsed = parse_jsonc(updated_text)
        assert parsed["editor.fontSize"] == 14
        customs = parsed["workbench.colorCustomizations"]
        assert customs["editor.background"] == "#1e1e1e"
        assert customs["activityBar.background"] == "#333333"

        # 3. Terminal colors injected
        assert customs["terminal.background"] == "#2e3440"
        assert customs["terminal.ansiMagenta"] == "#b48ead"

        # 4. Workbench theme set
        assert parsed["workbench.colorTheme"] == "Nord"


def test_adversarial_rapid_consecutive_updates_and_rollback() -> None:
    """Stress test: 5 consecutive theme updates in rapid succession with rollback."""
    with tempfile.TemporaryDirectory() as tmp_dir:
        wt_path = Path(tmp_dir) / "settings.json"
        wt_path.write_text('{\n  "profiles": { "list": [{ "name": "Omarchy" }] },\n  "schemes": []\n}', encoding="utf-8")

        themes = [TOKYO_NIGHT, CATPPUCCIN_MOCHA, NORD, TOKYO_NIGHT, CATPPUCCIN_MOCHA]
        for t in themes:
            res = sync_windows_terminal(wt_path, t, target_profile="Omarchy")
            assert res.success is True

        parsed = parse_jsonc(wt_path.read_text(encoding="utf-8"))
        omarchy_p = next(p for p in parsed["profiles"]["list"] if p["name"] == "Omarchy")
        assert omarchy_p["colorScheme"] == "Catppuccin Mocha"

        # Verify backup exists
        assert (wt_path.with_name("settings.json.bak")).exists()

        # Rollback
        restored = restore_from_backup(wt_path)
        assert restored is not None
        restored_parsed = parse_jsonc(wt_path.read_text(encoding="utf-8"))
        restored_p = next(p for p in restored_parsed["profiles"]["list"] if p["name"] == "Omarchy")
        # Previous was Tokyo Night
        assert restored_p["colorScheme"] == "Tokyo Night"


def test_cli_execution_adversarial_flows() -> None:
    """Verify CLI exit codes and behavior under various conditions."""
    cli_bin = Path(__file__).resolve().parent.parent / "bin" / "omarchy-theme-sync"
    assert cli_bin.exists()

    # 1. List themes exit code 0
    res = subprocess.run([sys.executable, str(cli_bin), "--list-themes"], capture_output=True, text=True)
    assert res.returncode == 0
    assert "tokyo-night" in res.stdout
    assert "nord" in res.stdout

    # 2. Status exit code 0
    res = subprocess.run([sys.executable, str(cli_bin), "--status"], capture_output=True, text=True)
    assert res.returncode == 0

    # 3. Invalid theme exit code 1
    res = subprocess.run([sys.executable, str(cli_bin), "--theme", "non-existent-theme"], capture_output=True, text=True)
    assert res.returncode == 1

    # 4. Dry run with valid theme exit code 0
    res = subprocess.run([sys.executable, str(cli_bin), "--theme", "tokyo-night", "--dry-run"], capture_output=True, text=True)
    assert res.returncode == 0
    assert "[DRY-RUN]" in res.stdout or "Tokyo Night" in res.stdout
