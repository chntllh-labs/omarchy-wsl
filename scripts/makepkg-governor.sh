#!/bin/bash
# ==============================================================================
# Omarchy WSL: Makepkg Build Governor & Dynamic Resource Arbiter
# ==============================================================================
# Prevents memory allocation starvation, OOM panics, and kswapd page allocation
# failures during heavy C++/Rust/Go package compilation on both constrained
# laptops (8GB-16GB RAM) and high-core workstations (Snapdragon X 12-core, Oryon 18-core).
# ==============================================================================

set -euo pipefail

PROFILE="${1:-standard}" # heavy, standard, light, auto

log() { echo -e "\e[34m[makepkg-governor]\e[0m $*"; }
warn() { echo -e "\e[33m[makepkg-governor:WARN]\e[0m $*"; }
success() { echo -e "\e[32m[makepkg-governor]\e[0m $*"; }

# ------------------------------------------------------------------------------
# 1. System Telemetry & Hardware Topology Discovery
# ------------------------------------------------------------------------------
get_total_ram_mb() {
  if [[ -f /proc/meminfo ]]; then
    awk '/MemTotal:/ {print int($2 / 1024)}' /proc/meminfo
  elif command -v free >/dev/null 2>&1; then
    free -m | awk '/^Mem:/{print $2}'
  elif command -v sysctl >/dev/null 2>&1; then
    # BSD / macOS fallback for testing
    local bytes
    bytes=$(sysctl -n hw.memsize 2>/dev/null || echo "8589934592")
    echo $(( bytes / 1024 / 1024 ))
  else
    echo 8192
  fi
}

get_cpu_cores() {
  if command -v nproc >/dev/null 2>&1; then
    nproc
  elif command -v getconf >/dev/null 2>&1; then
    getconf _NPROCESSORS_ONLN
  elif command -v sysctl >/dev/null 2>&1; then
    sysctl -n hw.ncpu 2>/dev/null || echo 4
  else
    echo 4
  fi
}

TOTAL_RAM_MB=$(get_total_ram_mb)
NPROC=$(get_cpu_cores)

log "Hardware Discovery: ${NPROC} logical cores detected, ${TOTAL_RAM_MB} MB total physical RAM."

# ------------------------------------------------------------------------------
# 2. Workload Profiling & Per-Thread Memory Weights
# ------------------------------------------------------------------------------
# Profiling memory demands per compilation unit:
# - heavy: Rust crates with LTO, modern C++20 (Chromium, LLVM, WebKit): 3072 MB / job
# - standard: Mixed C/C++, Neovim plugin tree-sitter grammars, Go with CGO: 2048 MB / job
# - light: Pure Go, shell packages, python, data-only, no LTO: 1024 MB / job
case "$PROFILE" in
  heavy)
    MEM_PER_THREAD_MB=3072
    ;;
  light)
    MEM_PER_THREAD_MB=1024
    ;;
  standard|auto|*)
    MEM_PER_THREAD_MB=2048
    ;;
esac

# ------------------------------------------------------------------------------
# 3. Dynamic Concurrency Derivation
# ------------------------------------------------------------------------------
# Reserve 15% RAM headroom for operating system, container runtime, and desktop services
USABLE_RAM_MB=$(( TOTAL_RAM_MB * 85 / 100 ))

# Calculate maximum safe compiler threads without risking swap death
MAX_MEM_THREADS=$(( USABLE_RAM_MB / MEM_PER_THREAD_MB ))
if (( MAX_MEM_THREADS < 1 )); then
  MAX_MEM_THREADS=1
fi

# Governor Clamp: Never exceed available CPU cores, never exceed safe RAM budget
if (( MAX_MEM_THREADS < NPROC )); then
  GOVERNED_JOBS=$MAX_MEM_THREADS
  CONSTRAINED=1
  warn "Memory constrained! Throttling concurrency from ${NPROC} to ${GOVERNED_JOBS} threads (${MEM_PER_THREAD_MB}MB budget/thread)."
else
  GOVERNED_JOBS=$NPROC
  CONSTRAINED=0
  success "Memory headroom sufficient. Utilizing full concurrency: ${GOVERNED_JOBS} threads."
fi

# Load Average Guard: make load threshold = NPROC + 1
LOAD_THRESHOLD=$(( NPROC + 1 ))

# ------------------------------------------------------------------------------
# 4. Generate Environment & makepkg Configuration
# ------------------------------------------------------------------------------
export MAKEFLAGS="-j${GOVERNED_JOBS} -l${LOAD_THRESHOLD}"
export NINJAFLAGS="-j${GOVERNED_JOBS}"
export CARGO_BUILD_JOBS="${GOVERNED_JOBS}"
export RUSTFLAGS="-C codegen-units=${GOVERNED_JOBS}"

# Drop-in configuration for makepkg if /etc/makepkg.conf.d exists
if [[ -d /etc/makepkg.conf.d && -w /etc/makepkg.conf.d ]]; then
  cat <<EOF > /etc/makepkg.conf.d/00-governor.conf
# Autogenerated by omarchy-makepkg-governor
MAKEFLAGS="-j${GOVERNED_JOBS} -l${LOAD_THRESHOLD}"
NINJAFLAGS="-j${GOVERNED_JOBS}"
CARGO_BUILD_JOBS="${GOVERNED_JOBS}"
RUSTFLAGS="-C codegen-units=${GOVERNED_JOBS}"
COMPRESSZST=(zstd -c -z -q --threads=${GOVERNED_JOBS} -)
EOF
  log "Wrote drop-in configuration to /etc/makepkg.conf.d/00-governor.conf"
fi

# ------------------------------------------------------------------------------
# 5. Sysctl Memory Defense Audit (Preventing 2026-09-10 Kernel Panic)
# ------------------------------------------------------------------------------
audit_sysctl_memory_guards() {
  if [[ -f /proc/sys/vm/vfs_cache_pressure ]]; then
    local vfs_pressure swappiness min_free
    vfs_pressure=$(cat /proc/sys/vm/vfs_cache_pressure)
    swappiness=$(cat /proc/sys/vm/swappiness)
    min_free=$(cat /proc/sys/vm/min_free_kbytes)

    if (( vfs_pressure < 100 )); then
      warn "Dangerous vfs_cache_pressure (${vfs_pressure}) detected! Inode cache may starve memory during compiles."
      if [[ -w /proc/sys/vm/vfs_cache_pressure ]]; then
        echo 100 > /proc/sys/vm/vfs_cache_pressure
        log "Corrected vm.vfs_cache_pressure to 100."
      fi
    fi

    if (( min_free < 65536 )); then
      warn "Low min_free_kbytes (${min_free}kB). Emergency watermark vulnerable to atomic allocation failure."
      if [[ -w /proc/sys/vm/min_free_kbytes ]]; then
        echo 131072 > /proc/sys/vm/min_free_kbytes
        log "Elevated vm.min_free_kbytes to 131072 kB."
      fi
    fi
  fi
}

audit_sysctl_memory_guards

# ------------------------------------------------------------------------------
# 6. Output Summary Block
# ------------------------------------------------------------------------------
cat <<EOF

========================================================================
 Omarchy-WSL Makepkg Build Governor Policy
========================================================================
 Total RAM         : ${TOTAL_RAM_MB} MB
 CPU Cores         : ${NPROC}
 Profile           : ${PROFILE} (${MEM_PER_THREAD_MB} MB/thread)
 Governed Jobs     : ${GOVERNED_JOBS}
 Load Guard        : -l${LOAD_THRESHOLD}
 Memory Constrained: $( (( CONSTRAINED == 1 )) && echo "YES" || echo "NO" )
 MAKEFLAGS         : $MAKEFLAGS
 CARGO_BUILD_JOBS  : $CARGO_BUILD_JOBS
========================================================================
EOF

# If called with command arguments (e.g. ./makepkg-governor.sh -- makepkg -sc), execute it
if [[ "${2:-}" == "--" ]]; then
  shift 2
  log "Executing wrapped command with governed resource bounds: $*"
  exec "$@"
fi
