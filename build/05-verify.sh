#!/usr/bin/env bash
# Step 05: prove the assembled system works before it is sealed. Every check
# here fails the build except the Neovim probe (it depends on plugin state
# omarchy-nvim pre-fetches, so it only warns).
#
#   - omarchy-theme-set (the WSL overlay over upstream v4.5.0's headless mode)
#     applies Tokyo Night in a probe home, then the theme bridge round-trips a
#     scratch Windows Terminal settings.json without losing comments.
#   - /usr/lib/wsl/terminal-profile.json equals what the bridge renders from
#     the pinned upstream theme, and both WSL files stay under WSL's 1 MiB cap.
#   - Every unit and slice this repository ships passes systemd-analyze verify
#     with no "Unknown" keys.
#   - The toolchain links (libc_nonshared.a / libgcc are intact).

# shellcheck source=SCRIPTDIR/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

ensure_builder
probe_home=$(mktemp -d /tmp/omarchy-probe.XXXXXX)
scratch=$(mktemp -d /tmp/omarchy-bridge.XXXXXX)
trap 'rm -rf "$probe_home" "$scratch"' EXIT
cp -a /etc/skel/. "$probe_home/"
chown -R "$BUILDER_USER:$BUILDER_USER" "$probe_home" "$scratch"

probe() {
  runuser -u "$BUILDER_USER" -- env -i HOME="$probe_home" PATH=/usr/local/bin:/usr/bin TERM=xterm-256color \
    LANG=C.UTF-8 OMARCHY_PATH=/usr/share/omarchy "$@"
}

log "omarchy-theme-set 'Tokyo Night' (headless WSL overlay over upstream $(lock OMARCHY_TAG))"
probe env OMARCHY_WSL_THEME_BRIDGE=0 omarchy-theme-set "Tokyo Night"
[[ $(<"$probe_home/.local/state/omarchy/current/theme.name") == tokyo-night ]] || die "theme.name is not tokyo-night"
[[ -s $probe_home/.local/state/omarchy/current/theme/colors.toml ]] || die "theme colors.toml missing"
probe omarchy-theme-list >/dev/null

log "Neovim starts headless with the Omarchy theme"
colors=$(probe timeout 180 nvim --headless "+lua io.write(vim.g.colors_name or '')" +qa 2>/dev/null | tail -n 1 || true)
if [[ $colors == *tokyonight* ]]; then
  log "nvim colorscheme: $colors"
else
  warn "nvim reported colorscheme '${colors:-none}' (expected tokyonight*); plugins sync on first interactive start"
fi

log "theme bridge self-test against a scratch Windows profile"
wt="$scratch/AppData/Local/Packages/Microsoft.WindowsTerminal_8wekyb3d8bbwe/LocalState"
install -d -o "$BUILDER_USER" -g "$BUILDER_USER" "$wt"
cat >"$wt/settings.json" <<'JSON'
// generated by Windows Terminal
{
    "profiles": { "list": [ { "name": "Omarchy", "source": "Microsoft.WSL" } ] },
    "schemes": []
}
JSON
chown "$BUILDER_USER:$BUILDER_USER" "$wt/settings.json"
probe omarchy-theme-bridge "Tokyo Night" --windows-home "$scratch" --profile Omarchy --no-vscode
grep -q '"colorScheme": "Omarchy ' "$wt/settings.json" || die "bridge did not switch the profile scheme"
grep -q '^// generated by Windows Terminal' "$wt/settings.json" || die "bridge dropped settings comments"

log "WSL distribution files"
probe omarchy-theme-bridge "Tokyo Night" --emit-terminal-profile >"$scratch/terminal-profile.json"
python3 -c 'import json,sys; a=json.load(open(sys.argv[1])); b=json.load(open(sys.argv[2])); sys.exit(a != b)' \
  "$scratch/terminal-profile.json" /usr/lib/wsl/terminal-profile.json ||
  die "/usr/lib/wsl/terminal-profile.json differs from the bridge's Tokyo Night rendering"
for f in /usr/lib/wsl/oobe.sh /usr/lib/wsl/omarchy.ico /usr/lib/wsl/terminal-profile.json; do
  size=$(stat -c %s "$f")
  ((size < 1048576)) || die "$f is $size bytes; WSL reads it with a 1 MiB limit"
  log "$f: $size bytes"
done

log "systemd-analyze verify (units shipped by this repository)"
units=(/etc/systemd/system/build.slice /usr/lib/systemd/user/build.slice)
while read -r path; do
  case "$path" in
    *.service | *.slice | *.socket | *.timer) units+=("$path") ;;
  esac
done < <(awk '{print $3}' /usr/share/omarchy-wsl/manifest-pkg.sha256)
analysis=$(SYSTEMD_LOG_LEVEL=warning systemd-analyze verify "${units[@]}" 2>&1 || true)
if grep -iE 'unknown (key|section|lvalue)|unknown assignment' <<<"$analysis"; then
  die "systemd-analyze reported unknown directives"
fi
log "verified ${#units[@]} units"

log "toolchain links a C program"
echo 'int main(void){return 0;}' | gcc -x c - -o "$scratch/t" && "$scratch/t"
